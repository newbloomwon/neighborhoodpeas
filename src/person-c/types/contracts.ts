export type SupportedLanguage = "en" | "es";

export type Borough =
  | "Brooklyn"
  | "Manhattan"
  | "Queens"
  | "Bronx"
  | "Staten Island";

/**
 * Emitted by Person A (3D Map & Walk Mode Lead) when the user enters a block or turns a corner.
 */
export interface BlockContext {
  blockId: string;
  streetName: string;
  fromCrossStreet: string;
  toCrossStreet: string;
  upcomingIntersection: string;
  borough: Borough;
  neighborhood: string;
  councilDistrict: number;
  councilMemberName: string;
  communityBoard: string;
  boundingBoxWKT: string;
  adjacentNextBlockId?: string;
}

/**
 * Returned by Person B (NYC Open Data Lead) from NYC 311 Service Requests (`erm2-nwe9`).
 */
export interface Block311Summary {
  blockId: string;
  timeWindowDays: number;
  totalComplaints: number;
  openComplaints: number;
  closedNoActionCount: number;
  repeatLocationCount: number;
  medianResponseHours: number;
  averageResponseHours: number;
  topDescriptors: {
    category: string;
    descriptor: string;
    plainLanguageLabel: { en: string; es: string };
    count: number;
  }[];
  sourceDatasetId: "erm2-nwe9";
  executedQuery: string;
}

/**
 * Returned by Person B (NYC Open Data Lead) from NYPD Motor Vehicle Collisions (`h9gi-nx95`).
 */
export interface IntersectionCrashSummary {
  intersectionId: string;
  intersectionName: string;
  timeWindowMonths: number;
  totalCrashes: number;
  pedestrianInjuries: number;
  cyclistInjuries: number;
  motoristInjuries: number;
  fatalities: number;
  dataThroughDate: string; // e.g., "2026-06-30" (~4 months behind current date)
  dataLagMonths: number;   // Typically 4
  sourceDatasetId: "h9gi-nx95";
  executedQuery: string;
}

/**
 * Streamed by Person C to Person E ("Glass Box AI" Live Telemetry Panel).
 */
export interface GlassBoxTraceEvent {
  stepId: string;
  timestampIso: string;
  agentName:
    | "SupervisorRouter"
    | "HonestByDesignGuardrail"
    | "WalkNarratorAgent"
    | "SafeRouteScoutAgent"
    | "AccountabilityLensAgent"
    | "ZeroHallucinationFactGate";
  actionSummary: string;
  executedQuery?: string;
  sourceDatasetId?: "erm2-nwe9" | "h9gi-nx95" | "nyc-council-boundaries";
  verifiedNumbers: number[];
  factCheckPassed: boolean;
  dataLagDisclosure?: string;
}

/**
 * Sent by Person C to Person D (Bilingual Voice Narrator) and Person F (Always-On Captions).
 */
export interface NarrationPayload {
  blockId: string;
  language: SupportedLanguage;
  spokenText: string;
  captionText: string;
  hasCornerWarning: boolean;
  dataLagNotice: string;
  prefetchedNextBlock?: {
    blockId: string;
    spokenText: string;
    captionText: string;
  };
  generatedInMs: number;
}

/**
 * Generated by Person C's AccountabilityLensAgent and rendered/exported by Person E in <10s.
 */
export interface AccountabilityReportPayload {
  reportId: string;
  generatedAtIso: string;
  generatedInMs: number;
  language: SupportedLanguage;
  targetArea: {
    neighborhood: string;
    borough: Borough;
    councilDistrict: number;
    councilMemberName: string;
    communityBoard: string;
    blocksAnalyzed: string[];
  };
  metrics: {
    total311Complaints: number;
    openComplaints: number;
    closedNoActionCount: number;
    closedNoActionPct: number;
    chronicRepeatLocations: number;
    medianAgencyResponseHours: number;
    totalRouteCrashes: number;
    pedestrianInjuries: number;
    cyclistInjuries: number;
    highRiskIntersections: string[];
  };
  executiveBrief: string;
  honestByDesignDisclaimer: string;
  citations: {
    datasetId: string;
    datasetName: string;
    executedQuery: string;
  }[];
}
